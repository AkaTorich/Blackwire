"""Собрать вики GitHub из тех же материалов, что и справка Blackwire.chm
(docs/, docs/en/, README, SDK, примеры, схемы данных).

    python tools/build_wiki.py [папка]        по умолчанию target/wiki

Страницы — Markdown для https://github.com/AkaTorich/Blackwire/wiki: русские и
английские парами, примеры SDK и схемы — общие. Ссылки между документами
переводятся на страницы вики, ссылки на прочие файлы — на файлы в репозитории.
Папку целиком копируют в клон Blackwire.wiki.git (лишние страницы удаляются).
"""
from pathlib import Path, PurePosixPath
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
REPO = 'https://github.com/AkaTorich/Blackwire'
OUT = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / 'target' / 'wiki'

# (файл в репозитории, страница, раздел меню)
RU = [
    ('README.ru.md', 'О-игре', 'Об игре'),
    ('docs/GAME.md', 'Игра', 'Руководство игрока'),
    ('docs/COMMANDS.md', 'Команды-терминала', 'Команды терминала'),
    ('docs/ADDER.md', 'Язык-Adder', 'Язык Adder'),
    ('docs/HACK.md', 'Механики-взлома', 'Механики взлома'),
    ('docs/ONLINE.md', 'Онлайн', 'Онлайн'),
    ('docs/STORY.md', 'Легенда', 'Легенда'),
    ('docs/SDK.md', 'SDK-плагинов', 'SDK плагинов'),
    ('sdk/README.md', 'Пакет-SDK', 'Пакет SDK'),
    ('plugins/README.md', 'Плагины', 'Каталог плагинов'),
    ('plugins/VULNERABILITY_CASES.md', 'Дела-с-уязвимостями', 'Дела с уязвимостями'),
]
EN = [
    ('README.md', 'About', 'About the game'),
    ('docs/en/GAME.md', 'Game', "Player's guide"),
    ('docs/en/COMMANDS.md', 'Terminal-commands', 'Terminal commands'),
    ('docs/en/ADDER.md', 'Adder-language', 'Adder language'),
    ('docs/en/HACK.md', 'Hacking-mechanics', 'Hacking mechanics'),
    ('docs/en/ONLINE.md', 'Online', 'Online'),
    ('docs/en/STORY.md', 'Story', 'Story'),
    ('docs/en/SDK.md', 'Plugin-SDK', 'Plugin SDK'),
    ('sdk/README.en.md', 'SDK-package', 'SDK package'),
    ('plugins/README.en.md', 'Plugins', 'Plugin catalog'),
    ('plugins/VULNERABILITY_CASES.en.md', 'Vulnerability-cases', 'Vulnerability cases'),
]
EXAMPLES = [
    ('device_lab', 'Устройства и уязвимости', 'Devices and vulnerabilities'),
    ('district', 'Район, задание, магазин, окно', 'District, mission, shop, window'),
    ('custom_vuln_type', 'Свой тип уязвимости', 'Custom vulnerability type'),
    ('access_lab', 'Результаты и условия доступа', 'Access results and conditions'),
]

PAGES = {}  # путь в репозитории → страница вики
for src, page, _ in RU + EN:
    PAGES[src] = page
for name, _, _ in EXAMPLES:
    PAGES['sdk/examples/' + name] = 'Example-' + name
PAGES['sdk/schema'] = 'Data-schemas'

LINK = re.compile(r'(!?)\[([^\]]*)\]\(([^)\s]+)\)')


def resolve(target, base):
    """Ссылку из файла `base` — на страницу вики или файл в репозитории."""
    if re.match(r'^[a-z]+:', target) or target.startswith('#'):
        return target
    path, _, anchor = target.partition('#')
    anchor = '#' + anchor if anchor else ''
    norm = PurePosixPath(base).parent.joinpath(path)
    parts = []
    for p in norm.parts:
        if p == '..':
            if parts:
                parts.pop()
        elif p != '.':
            parts.append(p)
    rel = '/'.join(parts).rstrip('/')
    if rel in PAGES:
        return PAGES[rel] + anchor
    kind = 'tree' if (ROOT / rel).is_dir() else 'blob'
    return f'{REPO}/{kind}/main/{rel}{anchor}'


def convert(text, base):
    """Переписать ссылки вне блоков кода."""
    out, code = [], False
    for line in text.splitlines():
        if line.lstrip().startswith('```'):
            code = not code
        if not code:
            line = LINK.sub(lambda m: f'{m[1]}[{m[2]}]({resolve(m[3], base)})', line)
        out.append(line)
    return '\n'.join(out) + '\n'


def source_note(src, en):
    url = f'{REPO}/blob/main/{src}'
    return (f'\n---\n_Source: [{src}]({url}) · generated by `tools/build_wiki.py`._\n' if en
            else f'\n---\n_Источник: [{src}]({url}) · собрано `tools/build_wiki.py`._\n')


def example_page(name, ru, en):
    folder = ROOT / 'sdk' / 'examples' / name
    parts = [f'# {name}\n',
             f'**{ru}** · _{en}_\n',
             f'Пример из SDK / SDK example: [`sdk/examples/{name}`]({REPO}/tree/main/sdk/examples/{name}). '
             'Как подключить — [Пакет SDK](Пакет-SDK) · How to use — [SDK package](SDK-package).\n']
    for f in sorted(folder.iterdir()):
        if f.suffix not in ('.json', '.adr', '.md'):
            continue
        lang = 'json' if f.suffix == '.json' else ('python' if f.suffix == '.adr' else 'markdown')
        body = f.read_text(encoding='utf-8-sig').rstrip()
        parts.append(f'## {f.name}\n\n```{lang}\n{body}\n```\n')
    return '\n'.join(parts)


def schema_page():
    parts = ['# Data schemas / Схемы данных\n',
             'Примеры сериализованных объектов ядра (API 1) — как в справке CHM. '
             'Examples of serialized core objects (API 1), as in the CHM help.\n',
             f'Папка / folder: [`sdk/schema`]({REPO}/tree/main/sdk/schema)\n']
    for f in sorted((ROOT / 'sdk' / 'schema').glob('*.json')):
        parts.append(f'## {f.stem}\n\n```json\n{f.read_text(encoding="utf-8-sig").rstrip()}\n```\n')
    return '\n'.join(parts)


def home():
    rows = '\n'.join(f'| [{r[2]}]({r[1]}) | [{e[2]}]({e[1]}) |' for r, e in zip(RU, EN))
    ex = '\n'.join(f'| [{ru}](Example-{n}) | [{en}](Example-{n}) |' for n, ru, en in EXAMPLES)
    return f"""# Blackwire

Хакерский симулятор с собственной операционной системой, живой игровой сетью и языком Adder — и онлайн в общем вымышленном мире.
A hacker simulator with its own operating system, a living game network and the Adder language — and online play in a shared fictional world.

[Скачать / Download]({REPO}/releases/latest) · [Сайт / Website](https://game.globthe.top/) · [Код / Source]({REPO})

| Русский | English |
| --- | --- |
{rows}

## Примеры SDK / SDK examples

| | |
| --- | --- |
{ex}
| [Схемы данных](Data-schemas) | [Data schemas](Data-schemas) |

Вики собирается из документов репозитория: правки вносятся в `docs/` и README, затем `python tools/build_wiki.py`.
The wiki is generated from the repository docs: edit `docs/` and the READMEs, then run `python tools/build_wiki.py`.
"""


def sidebar():
    ru = '\n'.join(f'- [{t}]({p})' for _, p, t in RU)
    en = '\n'.join(f'- [{t}]({p})' for _, p, t in EN)
    ex = '\n'.join(f'- [{n}](Example-{n})' for n, _, _ in EXAMPLES)
    return f'**[Blackwire](Home)**\n\n**Русский**\n{ru}\n\n**English**\n{en}\n\n**SDK**\n{ex}\n- [Data schemas](Data-schemas)\n'


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    for old in OUT.glob('*.md'):
        old.unlink()
    written = {}
    for group, en in ((RU, False), (EN, True)):
        for src, page, _ in group:
            text = (ROOT / src).read_text(encoding='utf-8-sig')
            written[page] = convert(text, src) + source_note(src, en)
    for name, ru, en in EXAMPLES:
        written['Example-' + name] = example_page(name, ru, en)
    written['Data-schemas'] = schema_page()
    written['Home'] = home()
    written['_Sidebar'] = sidebar()
    written['_Footer'] = f'[Blackwire]({REPO}) · [Releases]({REPO}/releases/latest) · [game.globthe.top](https://game.globthe.top/)\n'
    for page, text in written.items():
        (OUT / f'{page}.md').write_text(text, encoding='utf-8', newline='\n')
    # проверка: каждая ссылка на страницу вики ведёт на существующую страницу
    bad = []
    for page, text in written.items():
        for m in LINK.finditer(text):
            t = m[3].split('#')[0]
            if t and not re.match(r'^[a-z]+:', t) and t not in written:
                bad.append(f'{page}: {m[3]}')
    print(f'{len(written)} страниц → {OUT}')
    if bad:
        print('ссылки в никуда:\n  ' + '\n  '.join(bad))
        sys.exit(1)


if __name__ == '__main__':
    main()
