/// Ответ на `команда --help`, `help команда`, `man команда`.
pub fn command_help(info: &CmdInfo) -> CmdOutput {
    let mut out = CmdOutput::ok();
    out.push_kind(info.name.to_string(), OutKind::Heading);
    out.push_kind(format!("Использование: {}", info.usage), OutKind::Accent);
    out.push("");
    out.push(info.short.to_string());
    if let Some(long) = long_help(info.name) {
        out.push("");
        out.push(long.to_string());
    }
    out
}

/// Таблица команд для `help` без аргументов (по группам).
pub fn help_table() -> Vec<String> {
    let mut lines = Vec::new();
    lines.push("Команды Blackwire. Подробнее: help <команда> или <команда> --help.".to_string());
    for group in Group::all() {
        let cmds = by_group(group);
        if cmds.is_empty() {
            continue;
        }
        lines.push(format!("== {}", group.title()));
        let rows: Vec<Vec<String>> = cmds.iter().map(|c| vec![c.name.to_string(), c.short.to_string()]).collect();
        lines.extend(table(&rows, &[false, false]).into_iter().map(|l| format!("  {}", l)));
    }
    lines.push("== Оболочка".to_string());
    lines.push("  Конвейер a | b, перенаправления > >> 2> <, разделители ; && ||".to_string());
    lines.push("  Переменные $ИМЯ, ~ — домашняя папка, * и ? в именах файлов".to_string());
    lines
}

/// Markdown всех команд — для окна «Справка».
pub fn shell_doc() -> String {
    let mut s = String::from("# Команды терминала Blackwire\n\n");
    s.push_str("Оболочка понимает конвейеры (`a | b`), перенаправления (`>`, `>>`, `2>`, `<`), ");
    s.push_str("разделители (`;`, `&&`, `||`), переменные (`$ИМЯ`, `${ИМЯ}`), домашнюю папку (`~`) ");
    s.push_str("и подстановку `*`/`?` в именах файлов. У каждой команды есть `--help`.\n\n");
    for group in Group::all() {
        let cmds = by_group(group);
        if cmds.is_empty() {
            continue;
        }
        s.push_str(&format!("## {}\n\n", group.title()));
        s.push_str("| Команда | Использование | Назначение |\n|---|---|---|\n");
        for c in cmds {
            s.push_str(&format!("| `{}` | `{}` | {} |\n", c.name, c.usage, c.short));
        }
        s.push('\n');
    }
    s.push_str(&format!("\nВсего команд: {}.\n", COMMANDS.len()));
    s
}
