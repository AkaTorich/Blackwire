//! Сеть игры: машины, службы на портах, организации со своими подсетями,
//! DNS и генератор мира из зерна.
//!
//! Устройство модуля:
//! - `machine`       — `Machine`, виды машин, журнал, письма.
//! - `services`      — `Service`, веб-страницы, таблица уязвимых версий.
//! - `services_data` — таблицы служб: порты, версии, баннеры, наборы по видам машин.
//! - `orgs`          — `Org`, виды организаций, шаблоны.
//! - `orgs_data`     — таблицы шаблонов организаций (имена, домены, состав машин).
//! - `names`         — имена людей, слабые пароли, генератор сильных паролей.
//! - `files_data`    — шаблоны текстов файлов (заметки, история, документы).
//! - `web`           — сборка веб-страниц для http-служб.
//! - `mail`          — письма: ящик игрока и сотрудников.
//! - `gen`           — генератор мира: раскладка организаций, адреса, карта.
//! - `gen_machine`   — сборка одной машины: пользователи, файлы, службы, процессы, журнал.
//! - `player`        — компьютер игрока и его маршрутизатор.
//! - `player_data`   — тексты для компьютера игрока: readme, скрипты Adder.
//! - `dns`           — разрешение имён и обратный поиск.

